-- ============================================================
-- SCD TYPE 2: MERGE procedure for incremental updates
-- ============================================================

CREATE OR REPLACE PROCEDURE BANKING_GOV.SILVER.MERGE_CUSTOMER_SCD2()
RETURNS VARCHAR
LANGUAGE SQL
AS
BEGIN
    -- Step 1: Expire changed records
    UPDATE BANKING_GOV.SILVER.DIM_CUSTOMER_SCD2 tgt
    SET
        EFFECTIVE_TO = CURRENT_TIMESTAMP(),
        IS_CURRENT = FALSE,
        UPDATED_AT = CURRENT_TIMESTAMP()
    WHERE tgt.IS_CURRENT = TRUE
    AND EXISTS (
        SELECT 1 FROM BANKING_GOV.BRONZE.RAW_CUSTOMERS src
        WHERE src.CUSTOMER_ID = tgt.CUSTOMER_ID
        AND (
            TRIM(src.FIRST_NAME) != tgt.FIRST_NAME OR
            TRIM(src.LAST_NAME) != tgt.LAST_NAME OR
            src.EMAIL != tgt.EMAIL OR
            src.PHONE != tgt.PHONE OR
            src.ADDRESS != tgt.ADDRESS OR
            src.CITY != tgt.CITY OR
            TRY_TO_NUMBER(src.CREDIT_SCORE) != tgt.CREDIT_SCORE OR
            src.CUSTOMER_SEGMENT != tgt.CUSTOMER_SEGMENT
        )
    );

    -- Step 2: Insert new versions for changed records
    INSERT INTO BANKING_GOV.SILVER.DIM_CUSTOMER_SCD2 (
        CUSTOMER_ID, FIRST_NAME, LAST_NAME, FULL_NAME, SSN, EMAIL, PHONE,
        DATE_OF_BIRTH, ADDRESS, CITY, STATE, CREDIT_SCORE, CUSTOMER_SEGMENT,
        BRANCH_CODE, EFFECTIVE_FROM, IS_CURRENT, RECORD_VERSION
    )
    SELECT
        src.CUSTOMER_ID,
        TRIM(src.FIRST_NAME),
        TRIM(src.LAST_NAME),
        TRIM(src.FIRST_NAME) || ' ' || TRIM(src.LAST_NAME),
        src.SSN,
        LOWER(TRIM(src.EMAIL)),
        src.PHONE,
        TRY_TO_DATE(src.DATE_OF_BIRTH, 'YYYY-MM-DD'),
        src.ADDRESS,
        INITCAP(src.CITY),
        src.STATE,
        TRY_TO_NUMBER(src.CREDIT_SCORE),
        UPPER(src.CUSTOMER_SEGMENT),
        src.BRANCH_CODE,
        CURRENT_TIMESTAMP(),
        TRUE,
        COALESCE(hist.MAX_VERSION, 0) + 1
    FROM BANKING_GOV.BRONZE.RAW_CUSTOMERS src
    LEFT JOIN (
        SELECT CUSTOMER_ID, MAX(RECORD_VERSION) AS MAX_VERSION
        FROM BANKING_GOV.SILVER.DIM_CUSTOMER_SCD2
        GROUP BY CUSTOMER_ID
    ) hist ON src.CUSTOMER_ID = hist.CUSTOMER_ID
    WHERE NOT EXISTS (
        SELECT 1 FROM BANKING_GOV.SILVER.DIM_CUSTOMER_SCD2 tgt
        WHERE tgt.CUSTOMER_ID = src.CUSTOMER_ID
        AND tgt.IS_CURRENT = TRUE
    );

    RETURN 'SCD Type 2 merge completed successfully';
END;

-- ============================================================
-- SECTION 8: SILVER LAYER - SCD TYPE 1 (Account Dimension)
-- Overwrites with latest values, no history
-- ============================================================

-- SCD Type 1: Account dimension (overwrite)
CREATE OR REPLACE TABLE BANKING_GOV.SILVER.DIM_ACCOUNT_SCD1 (
    ACCOUNT_ID       VARCHAR(20) NOT NULL,
    CUSTOMER_ID      VARCHAR(20),
    ACCOUNT_NUMBER   VARCHAR(30),
    ACCOUNT_TYPE     VARCHAR(50),
    OPEN_DATE        DATE,
    STATUS           VARCHAR(20),
    CURRENT_BALANCE  NUMBER(15,2),
    INTEREST_RATE    NUMBER(5,2),
    BRANCH_CODE      VARCHAR(20),
    -- SCD Type 1 Metadata
    LAST_UPDATED_AT  TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Load SCD Type 1 with MERGE (upsert)
MERGE INTO BANKING_GOV.SILVER.DIM_ACCOUNT_SCD1 tgt
USING (
    SELECT
        ACCOUNT_ID,
        CUSTOMER_ID,
        ACCOUNT_NUMBER,
        UPPER(ACCOUNT_TYPE) AS ACCOUNT_TYPE,
        TRY_TO_DATE(OPEN_DATE, 'YYYY-MM-DD') AS OPEN_DATE,
        UPPER(STATUS) AS STATUS,
        TRY_TO_DECIMAL(BALANCE, 15, 2) AS CURRENT_BALANCE,
        TRY_TO_DECIMAL(INTEREST_RATE, 5, 2) AS INTEREST_RATE,
        BRANCH_CODE
    FROM BANKING_GOV.BRONZE.RAW_ACCOUNTS
) src
ON tgt.ACCOUNT_ID = src.ACCOUNT_ID
WHEN MATCHED THEN UPDATE SET
    tgt.STATUS = src.STATUS,
    tgt.CURRENT_BALANCE = src.CURRENT_BALANCE,
    tgt.INTEREST_RATE = src.INTEREST_RATE,
    tgt.LAST_UPDATED_AT = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (
    ACCOUNT_ID, CUSTOMER_ID, ACCOUNT_NUMBER, ACCOUNT_TYPE,
    OPEN_DATE, STATUS, CURRENT_BALANCE, INTEREST_RATE, BRANCH_CODE
) VALUES (
    src.ACCOUNT_ID, src.CUSTOMER_ID, src.ACCOUNT_NUMBER, src.ACCOUNT_TYPE,
    src.OPEN_DATE, src.STATUS, src.CURRENT_BALANCE, src.INTEREST_RATE, src.BRANCH_CODE
);

