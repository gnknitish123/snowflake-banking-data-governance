    TRY_TO_NUMBER(TERM_MONTHS),
    TRY_TO_DATE(DISBURSEMENT_DATE, 'YYYY-MM-DD'),
    BRANCH_CODE
FROM BANKING_GOV.BRONZE.RAW_LOANS;

-- SCD Type 3 update procedure
CREATE OR REPLACE PROCEDURE BANKING_GOV.SILVER.UPDATE_LOAN_SCD3(
    P_LOAN_ID VARCHAR,
    P_NEW_RATE NUMBER,
    P_NEW_STATUS VARCHAR,
    P_NEW_EMI NUMBER
)
RETURNS VARCHAR
LANGUAGE SQL
AS
BEGIN
    UPDATE BANKING_GOV.SILVER.DIM_LOAN_SCD3
    SET
        PREVIOUS_INTEREST_RATE = CURRENT_INTEREST_RATE,
        PREVIOUS_STATUS = CURRENT_STATUS,
        PREVIOUS_EMI = CURRENT_EMI,
        CURRENT_INTEREST_RATE = :P_NEW_RATE,
        CURRENT_STATUS = :P_NEW_STATUS,
        CURRENT_EMI = :P_NEW_EMI,
        LAST_CHANGE_DATE = CURRENT_TIMESTAMP(),
        LAST_UPDATED_AT = CURRENT_TIMESTAMP()
    WHERE LOAN_ID = :P_LOAN_ID;
    RETURN 'Loan ' || :P_LOAN_ID || ' updated with SCD Type 3 logic';
END;

