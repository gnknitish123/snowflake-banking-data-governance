-- Initial load for SCD Type 3
INSERT INTO BANKING_GOV.SILVER.DIM_LOAN_SCD3 (
    LOAN_ID, CUSTOMER_ID, LOAN_TYPE, PRINCIPAL,
    CURRENT_INTEREST_RATE, CURRENT_STATUS, CURRENT_EMI,
    PREVIOUS_INTEREST_RATE, PREVIOUS_STATUS, PREVIOUS_EMI,
    TERM_MONTHS, DISBURSEMENT_DATE, BRANCH_CODE
)
SELECT
    LOAN_ID,
    CUSTOMER_ID,
    UPPER(LOAN_TYPE),
    TRY_TO_DECIMAL(PRINCIPAL, 15, 2),
