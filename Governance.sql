CREATE OR REPLACE MASKING POLICY BANKING_GOV.GOVERNANCE.MASK_SSN AS
(VAL STRING) RETURNS STRING ->
    CASE
        WHEN CURRENT_ROLE() IN ('ACCOUNTADMIN', 'BANK_COMPLIANCE_ROLE') THEN VAL
        ELSE 'XXX-XX-' || RIGHT(VAL, 4)
    END;

-- Mask for email (partial)
CREATE OR REPLACE MASKING POLICY BANKING_GOV.GOVERNANCE.MASK_EMAIL AS
(VAL STRING) RETURNS STRING ->
    CASE
        WHEN CURRENT_ROLE() IN ('ACCOUNTADMIN', 'BANK_COMPLIANCE_ROLE') THEN VAL
        ELSE CONCAT(LEFT(VAL, 2), '****@', SPLIT_PART(VAL, '@', 2))
    END;

-- Mask for phone numbers
CREATE OR REPLACE MASKING POLICY BANKING_GOV.GOVERNANCE.MASK_PHONE AS
(VAL STRING) RETURNS STRING ->
    CASE
        WHEN CURRENT_ROLE() IN ('ACCOUNTADMIN', 'BANK_COMPLIANCE_ROLE') THEN VAL
        ELSE 'XXX-XXX-' || RIGHT(VAL, 4)
    END;

-- Mask for account numbers
CREATE OR REPLACE MASKING POLICY BANKING_GOV.GOVERNANCE.MASK_ACCOUNT_NUMBER AS
(VAL STRING) RETURNS STRING ->
    CASE
        WHEN CURRENT_ROLE() IN ('ACCOUNTADMIN', 'BANK_COMPLIANCE_ROLE', 'BANK_OPERATIONS_ROLE') THEN VAL
        ELSE 'XXXX-XXXX-' || RIGHT(VAL, 4)
    END;

-- Mask for monetary amounts (restricts to authorized roles)
CREATE OR REPLACE MASKING POLICY BANKING_GOV.GOVERNANCE.MASK_AMOUNT AS
(VAL NUMBER(15,2)) RETURNS NUMBER(15,2) ->
    CASE
        WHEN CURRENT_ROLE() IN ('ACCOUNTADMIN', 'BANK_COMPLIANCE_ROLE', 'BANK_OPERATIONS_ROLE') THEN VAL
        ELSE NULL
    END;






CREATE OR REPLACE ROW ACCESS POLICY BANKING_GOV.GOVERNANCE.BRANCH_ACCESS_POLICY AS
(BRANCH_CODE VARCHAR) RETURNS BOOLEAN ->
    CURRENT_ROLE() IN ('ACCOUNTADMIN', 'BANK_COMPLIANCE_ROLE')
    OR EXISTS (
        SELECT 1 FROM BANKING_GOV.GOVERNANCE.ROLE_BRANCH_MAPPING
        WHERE ROLE_NAME = CURRENT_ROLE()
        AND BRANCH = BRANCH_CODE
    );

