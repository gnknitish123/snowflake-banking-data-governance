CREATE OR REPLACE TABLE BANKING_GOV.SILVER.FACT_TRANSACTIONS AS
SELECT
    TRANSACTION_ID,
    ACCOUNT_ID,
    TRY_TO_TIMESTAMP(TRANSACTION_DATE, 'YYYY-MM-DD HH24:MI:SS') AS TRANSACTION_TIMESTAMP,
    TO_DATE(TRY_TO_TIMESTAMP(TRANSACTION_DATE, 'YYYY-MM-DD HH24:MI:SS')) AS TRANSACTION_DATE,
    UPPER(TRANSACTION_TYPE) AS TRANSACTION_TYPE,
    TRY_TO_DECIMAL(AMOUNT, 15, 2) AS AMOUNT,
    TRY_TO_DECIMAL(BALANCE_AFTER, 15, 2) AS BALANCE_AFTER,
    TRIM(DESCRIPTION) AS DESCRIPTION,
    UPPER(CHANNEL) AS CHANNEL,
    UPPER(STATUS) AS STATUS,
    CASE WHEN UPPER(STATUS) = 'FLAGGED' THEN TRUE ELSE FALSE END AS IS_SUSPICIOUS,
    CURRENT_TIMESTAMP() AS PROCESSED_AT
FROM BANKING_GOV.BRONZE.RAW_TRANSACTIONS
WHERE TRY_TO_TIMESTAMP(TRANSACTION_DATE, 'YYYY-MM-DD HH24:MI:SS') IS NOT NULL;

