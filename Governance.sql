USE SCHEMA BANKING_GOV.GOLD;

-- Customer Portfolio Summary (360 View)
CREATE OR REPLACE TABLE BANKING_GOV.GOLD.CUSTOMER_PORTFOLIO AS
SELECT
    c.CUSTOMER_ID,
    c.FULL_NAME,
    c.CITY,
    c.CUSTOMER_SEGMENT,
    c.CREDIT_SCORE,
    c.BRANCH_CODE,
    COUNT(DISTINCT a.ACCOUNT_ID) AS TOTAL_ACCOUNTS,
    SUM(a.CURRENT_BALANCE) AS TOTAL_BALANCE,
    COUNT(DISTINCT l.LOAN_ID) AS ACTIVE_LOANS,
    SUM(l.PRINCIPAL) AS TOTAL_LOAN_EXPOSURE,
    SUM(l.CURRENT_EMI) AS MONTHLY_EMI_BURDEN,
    ROUND(DIV0NULL(SUM(l.CURRENT_EMI), SUM(a.CURRENT_BALANCE)) * 100, 2) AS EMI_TO_BALANCE_RATIO
FROM BANKING_GOV.SILVER.DIM_CUSTOMER_SCD2 c
LEFT JOIN BANKING_GOV.SILVER.DIM_ACCOUNT_SCD1 a ON c.CUSTOMER_ID = a.CUSTOMER_ID
LEFT JOIN BANKING_GOV.SILVER.DIM_LOAN_SCD3 l ON c.CUSTOMER_ID = l.CUSTOMER_ID
WHERE c.IS_CURRENT = TRUE
GROUP BY c.CUSTOMER_ID, c.FULL_NAME, c.CITY, c.CUSTOMER_SEGMENT, c.CREDIT_SCORE, c.BRANCH_CODE;

-- Branch Performance Dashboard
CREATE OR REPLACE TABLE BANKING_GOV.GOLD.BRANCH_PERFORMANCE AS
SELECT
    a.BRANCH_CODE,
    COUNT(DISTINCT a.CUSTOMER_ID) AS TOTAL_CUSTOMERS,
    COUNT(DISTINCT a.ACCOUNT_ID) AS TOTAL_ACCOUNTS,
    SUM(a.CURRENT_BALANCE) AS TOTAL_DEPOSITS,
    SUM(CASE WHEN a.ACCOUNT_TYPE = 'SAVINGS' THEN a.CURRENT_BALANCE ELSE 0 END) AS SAVINGS_DEPOSITS,
    SUM(CASE WHEN a.ACCOUNT_TYPE = 'CURRENT' THEN a.CURRENT_BALANCE ELSE 0 END) AS CURRENT_DEPOSITS,
    SUM(CASE WHEN a.ACCOUNT_TYPE = 'FD' THEN a.CURRENT_BALANCE ELSE 0 END) AS FD_DEPOSITS,
    COUNT(DISTINCT CASE WHEN a.STATUS = 'DORMANT' THEN a.ACCOUNT_ID END) AS DORMANT_ACCOUNTS
FROM BANKING_GOV.SILVER.DIM_ACCOUNT_SCD1 a
GROUP BY a.BRANCH_CODE;

-- Transaction Analytics
CREATE OR REPLACE TABLE BANKING_GOV.GOLD.TRANSACTION_ANALYTICS AS
SELECT
    t.TRANSACTION_DATE,
    t.CHANNEL,
    t.TRANSACTION_TYPE,
    COUNT(*) AS TRANSACTION_COUNT,
    SUM(t.AMOUNT) AS TOTAL_AMOUNT,
    AVG(t.AMOUNT) AS AVG_AMOUNT,
    MAX(t.AMOUNT) AS MAX_AMOUNT,
    SUM(CASE WHEN t.IS_SUSPICIOUS THEN 1 ELSE 0 END) AS SUSPICIOUS_COUNT,
    SUM(CASE WHEN t.IS_SUSPICIOUS THEN t.AMOUNT ELSE 0 END) AS SUSPICIOUS_AMOUNT
FROM BANKING_GOV.SILVER.FACT_TRANSACTIONS t
GROUP BY t.TRANSACTION_DATE, t.CHANNEL, t.TRANSACTION_TYPE;

-- AML (Anti-Money Laundering) Suspicious Activity Report
CREATE OR REPLACE VIEW BANKING_GOV.GOLD.V_SUSPICIOUS_ACTIVITY AS
SELECT
    t.TRANSACTION_ID,
    t.TRANSACTION_TIMESTAMP,
    t.AMOUNT,
    t.DESCRIPTION,
    t.CHANNEL,
    a.ACCOUNT_NUMBER,
    a.ACCOUNT_TYPE,
    c.FULL_NAME AS CUSTOMER_NAME,
    c.BRANCH_CODE,
    c.CREDIT_SCORE,
    CASE
        WHEN t.AMOUNT > 100000 THEN 'HIGH_VALUE'
        WHEN t.IS_SUSPICIOUS THEN 'SYSTEM_FLAGGED'
        ELSE 'REVIEW'
    END AS ALERT_TYPE
FROM BANKING_GOV.SILVER.FACT_TRANSACTIONS t
JOIN BANKING_GOV.SILVER.DIM_ACCOUNT_SCD1 a ON t.ACCOUNT_ID = a.ACCOUNT_ID
JOIN BANKING_GOV.SILVER.DIM_CUSTOMER_SCD2 c ON a.CUSTOMER_ID = c.CUSTOMER_ID AND c.IS_CURRENT = TRUE
WHERE t.IS_SUSPICIOUS = TRUE OR t.AMOUNT > 100000;

-- Loan Book Summary
CREATE OR REPLACE TABLE BANKING_GOV.GOLD.LOAN_BOOK_SUMMARY AS
SELECT
    l.LOAN_TYPE,
    l.BRANCH_CODE,
    COUNT(*) AS LOAN_COUNT,
    SUM(l.PRINCIPAL) AS TOTAL_PRINCIPAL,
    AVG(l.CURRENT_INTEREST_RATE) AS AVG_INTEREST_RATE,
    SUM(l.CURRENT_EMI) AS TOTAL_MONTHLY_EMI,
    COUNT(CASE WHEN l.CURRENT_STATUS = 'ACTIVE' THEN 1 END) AS ACTIVE_LOANS,
    COUNT(CASE WHEN l.CURRENT_STATUS = 'NPA' THEN 1 END) AS NPA_LOANS
FROM BANKING_GOV.SILVER.DIM_LOAN_SCD3 l
GROUP BY l.LOAN_TYPE, l.BRANCH_CODE;

