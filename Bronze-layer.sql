CREATE TABLE IF NOT EXISTS RAW_CUSTOMERS (
    CUSTOMER_ID       VARCHAR(20),
    FIRST_NAME        VARCHAR(100),
    LAST_NAME         VARCHAR(100),
    SSN               VARCHAR(20),
    EMAIL             VARCHAR(200),
    PHONE             VARCHAR(20),
    DATE_OF_BIRTH     VARCHAR(20),
    ADDRESS           VARCHAR(500),
    CITY              VARCHAR(100),
    STATE             VARCHAR(50),
    CREDIT_SCORE      VARCHAR(20),
    CUSTOMER_SEGMENT  VARCHAR(50),
    BRANCH_CODE       VARCHAR(20),
    INGESTED_AT       TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);




CREATE TABLE IF NOT EXISTS RAW_ACCOUNTS (
    ACCOUNT_ID      VARCHAR(20),
    CUSTOMER_ID     VARCHAR(20),
    ACCOUNT_NUMBER  VARCHAR(30),
    ACCOUNT_TYPE    VARCHAR(50),
    OPEN_DATE       VARCHAR(20),
    STATUS          VARCHAR(20),
    BALANCE         VARCHAR(30),
    INTEREST_RATE   VARCHAR(20),
    BRANCH_CODE     VARCHAR(20),
    INGESTED_AT     TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);




CREATE TABLE IF NOT EXISTS RAW_TRANSACTIONS (
    TRANSACTION_ID    VARCHAR(30),
    ACCOUNT_ID        VARCHAR(20),
    TRANSACTION_DATE  VARCHAR(30),
    TRANSACTION_TYPE  VARCHAR(50),
    AMOUNT            VARCHAR(30),
    BALANCE_AFTER     VARCHAR(30),
    DESCRIPTION       VARCHAR(500),
    CHANNEL           VARCHAR(50),
    STATUS            VARCHAR(30),
    INGESTED_AT       TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);





CREATE TABLE IF NOT EXISTS RAW_LOANS (
    LOAN_ID             VARCHAR(20),
    CUSTOMER_ID         VARCHAR(20),
    LOAN_TYPE           VARCHAR(50),
    PRINCIPAL           VARCHAR(30),
    INTEREST_RATE       VARCHAR(20),
    STATUS              VARCHAR(30),
    EMI                 VARCHAR(30),
    TERM_MONTHS         VARCHAR(20),
    DISBURSEMENT_DATE   VARCHAR(20),
    BRANCH_CODE         VARCHAR(20),
    INGESTED_AT         TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);


