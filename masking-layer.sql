-- =========================================================
-- STEP 3: CREATE SSN MASKING POLICY
-- =========================================================

CREATE MASKING POLICY IF NOT EXISTS
BANKING_GOV.GOVERNANCE.MASK_SSN
AS (VAL VARCHAR)
RETURNS VARCHAR ->
    CASE
        WHEN CURRENT_ROLE() IN (
            'ACCOUNTADMIN',
            'BANK_COMPLIANCE_ROLE'
        )
        THEN VAL
        ELSE 'XXX-XX-' || RIGHT(VAL, 4)
    END;


-- =========================================================
-- STEP 4: CREATE EMAIL MASKING POLICY
-- =========================================================

CREATE MASKING POLICY IF NOT EXISTS
BANKING_GOV.GOVERNANCE.MASK_EMAIL
AS (VAL VARCHAR)
RETURNS VARCHAR ->
    CASE
        WHEN CURRENT_ROLE() IN (
            'ACCOUNTADMIN',
            'BANK_COMPLIANCE_ROLE'
        )
        THEN VAL
        ELSE CONCAT(
            LEFT(VAL, 2),
            '****@',
            SPLIT_PART(VAL, '@', 2)
        )
    END;


