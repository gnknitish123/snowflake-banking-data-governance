CREATE OR REPLACE ROW ACCESS POLICY
BANKING_GOV.GOVERNANCE.BRANCH_ACCESS_POLICY
AS (BRANCH_CODE VARCHAR)
RETURNS BOOLEAN ->
    CASE
        WHEN CURRENT_ROLE() IN (
            'ACCOUNTADMIN',
            'BANK_COMPLIANCE_ROLE'
        )
        THEN TRUE

        ELSE EXISTS (
            SELECT 1
            FROM BANKING_GOV.GOVERNANCE.ROLE_BRANCH_MAPPING M
            WHERE M.ROLE_NAME = CURRENT_ROLE()
              AND M.BRANCH_CODE = BRANCH_CODE
        )
    END;


