USE ROLE ACCOUNTADMIN;
USE WAREHOUSE COMPUTE_WH;
USE DATABASE BANKING_GOV;
USE SCHEMA GOLD;

CREATE TABLE IF NOT EXISTS CUSTOMER_PORTFOLIO (
    CUSTOMER_ID       VARCHAR(20),
    CUSTOMER_NAME     VARCHAR(200),
    CITY              VARCHAR(100),
    STATE             VARCHAR(50),
    CUSTOMER_SEGMENT  VARCHAR(50),
    CREDIT_SCORE      NUMBER(5,0),
    TOTAL_ACCOUNTS    NUMBER,
    TOTAL_BALANCE     NUMBER(18,2),
    TOTAL_LOANS       NUMBER,
    TOTAL_LOAN_AMOUNT NUMBER(18,2),
    PORTFOLIO_CREATED_AT TIMESTAMP_NTZ
);


INSERT INTO BANKING_GOV.GOLD.CUSTOMER_PORTFOLIO
SELECT
    C.CUSTOMER_ID,
    C.FIRST_NAME || ' ' || C.LAST_NAME,
    C.CITY,
    C.STATE,
    C.CUSTOMER_SEGMENT,
    C.CREDIT_SCORE,
    COALESCE(A.TOTAL_ACCOUNTS, 0),
    COALESCE(A.TOTAL_BALANCE, 0),
    COALESCE(L.TOTAL_LOANS, 0),
    COALESCE(L.TOTAL_LOAN_AMOUNT, 0),
    CURRENT_TIMESTAMP()

FROM BANKING_GOV.SILVER.DIM_CUSTOMER_SCD2 C

LEFT JOIN (
    SELECT
        CUSTOMER_ID,
        COUNT(*) AS TOTAL_ACCOUNTS,
        SUM(CURRENT_BALANCE) AS TOTAL_BALANCE
    FROM BANKING_GOV.SILVER.DIM_ACCOUNT_SCD1
    GROUP BY CUSTOMER_ID
) A
    ON C.CUSTOMER_ID = A.CUSTOMER_ID

LEFT JOIN (
    SELECT
        CUSTOMER_ID,
        COUNT(*) AS TOTAL_LOANS,
        SUM(PRINCIPAL) AS TOTAL_LOAN_AMOUNT
    FROM BANKING_GOV.SILVER.DIM_LOAN_SCD3
    GROUP BY CUSTOMER_ID
) L
    ON C.CUSTOMER_ID = L.CUSTOMER_ID

WHERE C.IS_CURRENT = TRUE;


SELECT *
FROM BANKING_GOV.GOLD.CUSTOMER_PORTFOLIO
ORDER BY CUSTOMER_ID;



SELECT
    COUNT(*) AS TOTAL_CUSTOMERS,
    SUM(TOTAL_ACCOUNTS) AS TOTAL_ACCOUNTS,
    SUM(TOTAL_BALANCE) AS TOTAL_CUSTOMER_BALANCE,
    SUM(TOTAL_LOANS) AS TOTAL_LOANS,
    SUM(TOTAL_LOAN_AMOUNT) AS TOTAL_LOAN_PRINCIPAL
FROM BANKING_GOV.GOLD.CUSTOMER_PORTFOLIO;







CREATE TABLE IF NOT EXISTS BRANCH_PERFORMANCE (
    BRANCH_CODE          VARCHAR(20),
    TOTAL_CUSTOMERS      NUMBER,
    TOTAL_ACCOUNTS       NUMBER,
    ACTIVE_ACCOUNTS      NUMBER,
    DORMANT_ACCOUNTS     NUMBER,
    TOTAL_DEPOSITS       NUMBER(18,2),
    AVG_ACCOUNT_BALANCE  NUMBER(18,2),
    REPORT_CREATED_AT    TIMESTAMP_NTZ
);


INSERT INTO BANKING_GOV.GOLD.BRANCH_PERFORMANCE
SELECT
    A.BRANCH_CODE,
    COUNT(DISTINCT A.CUSTOMER_ID) AS TOTAL_CUSTOMERS,
    COUNT(*) AS TOTAL_ACCOUNTS,
    COUNT_IF(A.STATUS = 'ACTIVE') AS ACTIVE_ACCOUNTS,
    COUNT_IF(A.STATUS = 'DORMANT') AS DORMANT_ACCOUNTS,
    SUM(A.CURRENT_BALANCE) AS TOTAL_DEPOSITS,
    AVG(A.CURRENT_BALANCE) AS AVG_ACCOUNT_BALANCE,
    CURRENT_TIMESTAMP()

FROM BANKING_GOV.SILVER.DIM_ACCOUNT_SCD1 A

GROUP BY A.BRANCH_CODE;


SELECT *
FROM BANKING_GOV.GOLD.BRANCH_PERFORMANCE
ORDER BY TOTAL_DEPOSITS DESC;





CREATE TABLE IF NOT EXISTS TRANSACTION_ANALYTICS (
    TRANSACTION_TYPE    VARCHAR(50),
    CHANNEL             VARCHAR(50),
    TOTAL_TRANSACTIONS  NUMBER,
    SUCCESS_COUNT       NUMBER,
    FLAGGED_COUNT       NUMBER,
    TOTAL_AMOUNT        NUMBER(18,2),
    AVG_AMOUNT          NUMBER(18,2),
    REPORT_CREATED_AT   TIMESTAMP_NTZ
);


INSERT INTO BANKING_GOV.GOLD.TRANSACTION_ANALYTICS
SELECT
    TRANSACTION_TYPE,
    CHANNEL,
    COUNT(*) AS TOTAL_TRANSACTIONS,
    COUNT_IF(STATUS = 'SUCCESS') AS SUCCESS_COUNT,
    COUNT_IF(STATUS = 'FLAGGED') AS FLAGGED_COUNT,
    SUM(AMOUNT) AS TOTAL_AMOUNT,
    AVG(AMOUNT) AS AVG_AMOUNT,
    CURRENT_TIMESTAMP()

FROM BANKING_GOV.SILVER.FACT_TRANSACTIONS

GROUP BY
    TRANSACTION_TYPE,
    CHANNEL;

SELECT *
FROM BANKING_GOV.GOLD.TRANSACTION_ANALYTICS
ORDER BY TOTAL_AMOUNT DESC;


SELECT
    SUM(TOTAL_TRANSACTIONS) AS TOTAL_TRANSACTIONS,
    SUM(SUCCESS_COUNT) AS SUCCESS_TRANSACTIONS,
    SUM(FLAGGED_COUNT) AS FLAGGED_TRANSACTIONS,
    SUM(TOTAL_AMOUNT) AS TOTAL_AMOUNT
FROM BANKING_GOV.GOLD.TRANSACTION_ANALYTICS;



CREATE OR REPLACE VIEW V_SUSPICIOUS_ACTIVITY AS
SELECT
    T.TRANSACTION_ID,
    T.ACCOUNT_ID,
    A.CUSTOMER_ID,
    C.FIRST_NAME || ' ' || C.LAST_NAME AS CUSTOMER_NAME,
    T.TRANSACTION_DATE,
    T.TRANSACTION_TYPE,
    T.AMOUNT,
    T.CHANNEL,
    T.STATUS,
    T.IS_SUSPICIOUS,
    A.BRANCH_CODE

FROM BANKING_GOV.SILVER.FACT_TRANSACTIONS T

LEFT JOIN BANKING_GOV.SILVER.DIM_ACCOUNT_SCD1 A
    ON T.ACCOUNT_ID = A.ACCOUNT_ID

LEFT JOIN BANKING_GOV.SILVER.DIM_CUSTOMER_SCD2 C
    ON A.CUSTOMER_ID = C.CUSTOMER_ID
   AND C.IS_CURRENT = TRUE

WHERE T.IS_SUSPICIOUS = TRUE;


SELECT *
FROM BANKING_GOV.GOLD.V_SUSPICIOUS_ACTIVITY;




CREATE TABLE IF NOT EXISTS LOAN_BOOK_SUMMARY (
    LOAN_TYPE          VARCHAR(50),
    CURRENT_STATUS     VARCHAR(30),
    TOTAL_LOANS        NUMBER,
    TOTAL_PRINCIPAL    NUMBER(18,2),
    AVG_INTEREST_RATE  NUMBER(5,2),
    TOTAL_MONTHLY_EMI  NUMBER(18,2),
    REPORT_CREATED_AT  TIMESTAMP_NTZ
);


INSERT INTO BANKING_GOV.GOLD.LOAN_BOOK_SUMMARY
SELECT
    LOAN_TYPE,
    CURRENT_STATUS,
    COUNT(*) AS TOTAL_LOANS,
    SUM(PRINCIPAL) AS TOTAL_PRINCIPAL,
    AVG(INTEREST_RATE) AS AVG_INTEREST_RATE,
    SUM(CURRENT_EMI) AS TOTAL_MONTHLY_EMI,
    CURRENT_TIMESTAMP()

FROM BANKING_GOV.SILVER.DIM_LOAN_SCD3

GROUP BY
    LOAN_TYPE,
    CURRENT_STATUS;


SELECT *
FROM BANKING_GOV.GOLD.LOAN_BOOK_SUMMARY
ORDER BY LOAN_TYPE, CURRENT_STATUS;

SELECT
    SUM(TOTAL_LOANS) AS TOTAL_LOANS,
    SUM(TOTAL_PRINCIPAL) AS TOTAL_LOAN_PRINCIPAL,
    SUM(TOTAL_MONTHLY_EMI) AS TOTAL_MONTHLY_EMI
FROM BANKING_GOV.GOLD.LOAN_BOOK_SUMMARY;


SELECT 'CUSTOMER_PORTFOLIO' AS OBJECT_NAME,
       COUNT(*) AS TOTAL_RECORDS
FROM BANKING_GOV.GOLD.CUSTOMER_PORTFOLIO

UNION ALL

SELECT 'BRANCH_PERFORMANCE', COUNT(*)
FROM BANKING_GOV.GOLD.BRANCH_PERFORMANCE

UNION ALL

SELECT 'TRANSACTION_ANALYTICS', COUNT(*)
FROM BANKING_GOV.GOLD.TRANSACTION_ANALYTICS

UNION ALL

SELECT 'V_SUSPICIOUS_ACTIVITY', COUNT(*)
FROM BANKING_GOV.GOLD.V_SUSPICIOUS_ACTIVITY

UNION ALL

SELECT 'LOAN_BOOK_SUMMARY', COUNT(*)
FROM BANKING_GOV.GOLD.LOAN_BOOK_SUMMARY;