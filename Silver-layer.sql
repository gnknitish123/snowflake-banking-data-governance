CREATE TABLE IF NOT EXISTS FACT_TRANSACTIONS (
    TRANSACTION_ID    VARCHAR(30),
    ACCOUNT_ID        VARCHAR(20),
    TRANSACTION_DATE  TIMESTAMP_NTZ,
    TRANSACTION_TYPE  VARCHAR(50),
    AMOUNT            NUMBER(18,2),
    BALANCE_AFTER     NUMBER(18,2),
    DESCRIPTION       VARCHAR(500),
    CHANNEL           VARCHAR(50),
    STATUS            VARCHAR(30),
    IS_SUSPICIOUS     BOOLEAN,
    INGESTED_AT       TIMESTAMP_NTZ
);



INSERT INTO BANKING_GOV.SILVER.FACT_TRANSACTIONS (
    TRANSACTION_ID,
    ACCOUNT_ID,
    TRANSACTION_DATE,
    TRANSACTION_TYPE,
    AMOUNT,
    BALANCE_AFTER,
    DESCRIPTION,
    CHANNEL,
    STATUS,
    IS_SUSPICIOUS,
    INGESTED_AT
)
SELECT
    TRIM(TRANSACTION_ID),
    TRIM(ACCOUNT_ID),
    TRY_TO_TIMESTAMP_NTZ(TRANSACTION_DATE),
    UPPER(TRIM(TRANSACTION_TYPE)),
    TRY_TO_DECIMAL(AMOUNT, 18, 2),
    TRY_TO_DECIMAL(BALANCE_AFTER, 18, 2),
    TRIM(DESCRIPTION),
    UPPER(TRIM(CHANNEL)),
    UPPER(TRIM(STATUS)),

    CASE
        WHEN UPPER(TRIM(STATUS)) = 'FLAGGED'
             OR TRY_TO_DECIMAL(AMOUNT, 18, 2) >= 100000
        THEN TRUE
        ELSE FALSE
    END,

    CURRENT_TIMESTAMP()

FROM BANKING_GOV.BRONZE.RAW_TRANSACTIONS

WHERE NULLIF(TRIM(TRANSACTION_ID), '') IS NOT NULL
  AND NULLIF(TRIM(ACCOUNT_ID), '') IS NOT NULL
  AND TRY_TO_TIMESTAMP_NTZ(TRANSACTION_DATE) IS NOT NULL;


SELECT *
FROM BANKING_GOV.SILVER.FACT_TRANSACTIONS
ORDER BY TRANSACTION_DATE;

SELECT
    COUNT(*) AS TOTAL_TRANSACTIONS,
    COUNT_IF(STATUS = 'SUCCESS') AS SUCCESS_TRANSACTIONS,
    COUNT_IF(STATUS = 'FLAGGED') AS FLAGGED_TRANSACTIONS,
    COUNT_IF(IS_SUSPICIOUS = TRUE) AS SUSPICIOUS_TRANSACTIONS,
    SUM(AMOUNT) AS TOTAL_TRANSACTION_AMOUNT
FROM BANKING_GOV.SILVER.FACT_TRANSACTIONS;



