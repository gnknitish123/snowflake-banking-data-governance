CREATE TABLE IF NOT EXISTS DIM_ACCOUNT_SCD1 (
    ACCOUNT_ID       VARCHAR(20),
    CUSTOMER_ID      VARCHAR(20),
    ACCOUNT_NUMBER   VARCHAR(30),
    ACCOUNT_TYPE     VARCHAR(50),
    OPEN_DATE        DATE,
    STATUS           VARCHAR(20),
    CURRENT_BALANCE  NUMBER(18,2),
    INTEREST_RATE    NUMBER(5,2),
    BRANCH_CODE      VARCHAR(20),
    UPDATED_AT       TIMESTAMP_NTZ
);


MERGE INTO BANKING_GOV.SILVER.DIM_ACCOUNT_SCD1 AS T
USING (
    SELECT
        TRIM(ACCOUNT_ID) AS ACCOUNT_ID,
        TRIM(CUSTOMER_ID) AS CUSTOMER_ID,
        TRIM(ACCOUNT_NUMBER) AS ACCOUNT_NUMBER,
        UPPER(TRIM(ACCOUNT_TYPE)) AS ACCOUNT_TYPE,
        TRY_TO_DATE(OPEN_DATE) AS OPEN_DATE,
        UPPER(TRIM(STATUS)) AS STATUS,
        TRY_TO_DECIMAL(BALANCE, 18, 2) AS CURRENT_BALANCE,
        TRY_TO_DECIMAL(INTEREST_RATE, 5, 2) AS INTEREST_RATE,
        UPPER(TRIM(BRANCH_CODE)) AS BRANCH_CODE
    FROM BANKING_GOV.BRONZE.RAW_ACCOUNTS
) AS S
ON T.ACCOUNT_ID = S.ACCOUNT_ID

WHEN MATCHED THEN UPDATE SET
    T.CUSTOMER_ID = S.CUSTOMER_ID,
    T.ACCOUNT_NUMBER = S.ACCOUNT_NUMBER,
    T.ACCOUNT_TYPE = S.ACCOUNT_TYPE,
    T.OPEN_DATE = S.OPEN_DATE,
    T.STATUS = S.STATUS,
    T.CURRENT_BALANCE = S.CURRENT_BALANCE,
    T.INTEREST_RATE = S.INTEREST_RATE,
    T.BRANCH_CODE = S.BRANCH_CODE,
    T.UPDATED_AT = CURRENT_TIMESTAMP()

WHEN NOT MATCHED THEN INSERT (
    ACCOUNT_ID,
    CUSTOMER_ID,
    ACCOUNT_NUMBER,
    ACCOUNT_TYPE,
    OPEN_DATE,
    STATUS,
    CURRENT_BALANCE,
    INTEREST_RATE,
    BRANCH_CODE,
    UPDATED_AT
)
VALUES (
    S.ACCOUNT_ID,
    S.CUSTOMER_ID,
    S.ACCOUNT_NUMBER,
    S.ACCOUNT_TYPE,
    S.OPEN_DATE,
    S.STATUS,
    S.CURRENT_BALANCE,
    S.INTEREST_RATE,
    S.BRANCH_CODE,
    CURRENT_TIMESTAMP()
);

SELECT *
FROM BANKING_GOV.SILVER.DIM_ACCOUNT_SCD1
ORDER BY ACCOUNT_ID;

SELECT
    COUNT(*) AS TOTAL_ACCOUNTS,
    COUNT_IF(STATUS = 'ACTIVE') AS ACTIVE_ACCOUNTS,
    COUNT_IF(STATUS = 'DORMANT') AS DORMANT_ACCOUNTS,
    SUM(CURRENT_BALANCE) AS TOTAL_BALANCE
FROM BANKING_GOV.SILVER.DIM_ACCOUNT_SCD1;




