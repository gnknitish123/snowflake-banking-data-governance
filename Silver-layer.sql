CREATE OR REPLACE PROCEDURE BANKING_GOV.SILVER.MERGE_CUSTOMER_SCD2()
RETURNS VARCHAR
LANGUAGE SQL
AS
$$
DECLARE
    v_run_ts TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP();

BEGIN

    -- STEP 1: Expire existing customer records when details change

    UPDATE BANKING_GOV.SILVER.DIM_CUSTOMER_SCD2 s
    SET
        EFFECTIVE_TO = :v_run_ts,
        IS_CURRENT = FALSE
    FROM BANKING_GOV.BRONZE.RAW_CUSTOMERS r
    WHERE s.CUSTOMER_ID = TRIM(r.CUSTOMER_ID)
      AND s.IS_CURRENT = TRUE
      AND (
          s.FIRST_NAME       IS DISTINCT FROM INITCAP(TRIM(r.FIRST_NAME))
          OR s.LAST_NAME     IS DISTINCT FROM INITCAP(TRIM(r.LAST_NAME))
          OR s.SSN            IS DISTINCT FROM TRIM(r.SSN)
          OR s.EMAIL          IS DISTINCT FROM LOWER(TRIM(r.EMAIL))
          OR s.PHONE          IS DISTINCT FROM TRIM(r.PHONE)
          OR s.DATE_OF_BIRTH  IS DISTINCT FROM TRY_TO_DATE(r.DATE_OF_BIRTH)
          OR s.ADDRESS        IS DISTINCT FROM TRIM(r.ADDRESS)
          OR s.CITY           IS DISTINCT FROM INITCAP(TRIM(r.CITY))
          OR s.STATE          IS DISTINCT FROM INITCAP(TRIM(r.STATE))
          OR s.CREDIT_SCORE   IS DISTINCT FROM TRY_TO_NUMBER(r.CREDIT_SCORE)
          OR s.CUSTOMER_SEGMENT IS DISTINCT FROM UPPER(TRIM(r.CUSTOMER_SEGMENT))
          OR s.BRANCH_CODE    IS DISTINCT FROM UPPER(TRIM(r.BRANCH_CODE))
      );

    -- STEP 2: Insert new customers and changed customer versions

    INSERT INTO BANKING_GOV.SILVER.DIM_CUSTOMER_SCD2 (
        CUSTOMER_ID,
        FIRST_NAME,
        LAST_NAME,
        SSN,
        EMAIL,
        PHONE,
        DATE_OF_BIRTH,
        ADDRESS,
        CITY,
        STATE,
        CREDIT_SCORE,
        CUSTOMER_SEGMENT,
        BRANCH_CODE,
        EFFECTIVE_FROM,
        EFFECTIVE_TO,
        IS_CURRENT,
        RECORD_VERSION
    )
    SELECT
        TRIM(r.CUSTOMER_ID),
        INITCAP(TRIM(r.FIRST_NAME)),
        INITCAP(TRIM(r.LAST_NAME)),
        TRIM(r.SSN),
        LOWER(TRIM(r.EMAIL)),
        TRIM(r.PHONE),
        TRY_TO_DATE(r.DATE_OF_BIRTH),
        TRIM(r.ADDRESS),
        INITCAP(TRIM(r.CITY)),
        INITCAP(TRIM(r.STATE)),
        TRY_TO_NUMBER(r.CREDIT_SCORE),
        UPPER(TRIM(r.CUSTOMER_SEGMENT)),
        UPPER(TRIM(r.BRANCH_CODE)),
        :v_run_ts,
        '9999-12-31 00:00:00'::TIMESTAMP_NTZ,
        TRUE,
        COALESCE(
            (
                SELECT MAX(h.RECORD_VERSION)
                FROM BANKING_GOV.SILVER.DIM_CUSTOMER_SCD2 h
                WHERE h.CUSTOMER_ID = TRIM(r.CUSTOMER_ID)
            ), 0
        ) + 1
    FROM BANKING_GOV.BRONZE.RAW_CUSTOMERS r
    WHERE NOT EXISTS (
        SELECT 1
        FROM BANKING_GOV.SILVER.DIM_CUSTOMER_SCD2 s
        WHERE s.CUSTOMER_ID = TRIM(r.CUSTOMER_ID)
          AND s.IS_CURRENT = TRUE
    );

    RETURN 'Customer SCD Type 2 process completed successfully.';

END;
$$;


