CREATE OR REPLACE PROCEDURE BANKING_GOV.SILVER.MERGE_LOAN_SCD3()
RETURNS VARCHAR
LANGUAGE SQL
AS
$$
BEGIN

    MERGE INTO BANKING_GOV.SILVER.DIM_LOAN_SCD3 T

    USING (
        SELECT
            TRIM(LOAN_ID) AS LOAN_ID,
            TRIM(CUSTOMER_ID) AS CUSTOMER_ID,
            UPPER(TRIM(LOAN_TYPE)) AS LOAN_TYPE,
            TRY_TO_DECIMAL(PRINCIPAL, 18, 2) AS PRINCIPAL,
            TRY_TO_DECIMAL(INTEREST_RATE, 5, 2) AS INTEREST_RATE,
            UPPER(TRIM(STATUS)) AS CURRENT_STATUS,
            TRY_TO_DECIMAL(EMI, 18, 2) AS CURRENT_EMI,
            TRY_TO_NUMBER(TERM_MONTHS) AS TERM_MONTHS,
            TRY_TO_DATE(DISBURSEMENT_DATE) AS DISBURSEMENT_DATE,
            UPPER(TRIM(BRANCH_CODE)) AS BRANCH_CODE
        FROM BANKING_GOV.BRONZE.RAW_LOANS
    ) S

    ON T.LOAN_ID = S.LOAN_ID

    WHEN MATCHED AND (
        T.CURRENT_STATUS IS DISTINCT FROM S.CURRENT_STATUS
        OR T.CURRENT_EMI IS DISTINCT FROM S.CURRENT_EMI
    )
    THEN UPDATE SET

        T.PREVIOUS_STATUS = T.CURRENT_STATUS,
        T.CURRENT_STATUS = S.CURRENT_STATUS,

        T.PREVIOUS_EMI = T.CURRENT_EMI,
        T.CURRENT_EMI = S.CURRENT_EMI,

        T.CUSTOMER_ID = S.CUSTOMER_ID,
        T.LOAN_TYPE = S.LOAN_TYPE,
        T.PRINCIPAL = S.PRINCIPAL,
        T.INTEREST_RATE = S.INTEREST_RATE,
        T.TERM_MONTHS = S.TERM_MONTHS,
        T.DISBURSEMENT_DATE = S.DISBURSEMENT_DATE,
        T.BRANCH_CODE = S.BRANCH_CODE,

        T.UPDATED_AT = CURRENT_TIMESTAMP()

    WHEN NOT MATCHED THEN INSERT (
        LOAN_ID,
        CUSTOMER_ID,
        LOAN_TYPE,
        PRINCIPAL,
        INTEREST_RATE,
        CURRENT_STATUS,
        PREVIOUS_STATUS,
        CURRENT_EMI,
        PREVIOUS_EMI,
        TERM_MONTHS,
        DISBURSEMENT_DATE,
        BRANCH_CODE,
        UPDATED_AT
    )
    VALUES (
        S.LOAN_ID,
        S.CUSTOMER_ID,
        S.LOAN_TYPE,
        S.PRINCIPAL,
        S.INTEREST_RATE,
        S.CURRENT_STATUS,
        NULL,
        S.CURRENT_EMI,
        NULL,
        S.TERM_MONTHS,
        S.DISBURSEMENT_DATE,
        S.BRANCH_CODE,
        CURRENT_TIMESTAMP()
    );

    RETURN 'Loan SCD Type 3 process completed successfully.';

END;
$$;


CALL BANKING_GOV.SILVER.MERGE_LOAN_SCD3();


