CREATE OR REPLACE ROW ACCESS POLICY
BANKING_GOV.GOVERNANCE.TRANSACTION_BRANCH_POLICY
AS (ROW_ACCOUNT_ID VARCHAR)
RETURNS BOOLEAN ->
    CASE
        WHEN CURRENT_ROLE() IN (
            'ACCOUNTADMIN',
            'BANK_COMPLIANCE_ROLE',
            'BANK_OPERATIONS_ROLE'
        )
        THEN TRUE

        ELSE EXISTS (
            SELECT 1
            FROM BANKING_GOV.SILVER.DIM_ACCOUNT_SCD1 A
            JOIN BANKING_GOV.GOVERNANCE.ROLE_BRANCH_MAPPING M
                ON A.BRANCH_CODE = M.BRANCH_CODE
            WHERE A.ACCOUNT_ID = ROW_ACCOUNT_ID
              AND M.ROLE_NAME = CURRENT_ROLE()
        )
    END;




